#[test]
fn evidence_pack_with_zero_citations_still_produces_valid_zip() {
    let dir = tempfile::tempdir().unwrap();
    let output = dir.path().join("evidence.zip");
    let artifact = Artifact::new("No Citations".into(), ArtifactType::Document, None);

    build_evidence_pack(&artifact, &[], output.to_str().unwrap()).expect("build_evidence_pack");

    let file = std::fs::File::open(&output).unwrap();
    let mut archive = zip::ZipArchive::new(file).expect("zip parses");
    let names: Vec<String> = (0..archive.len())
        .map(|i| archive.by_index(i).unwrap().name().to_string())
        .collect();
    assert!(names.contains(&"artifact.md".to_string()));
    assert!(names.contains(&"citations.json".to_string()));
    // No sources/ entries when there are no citations.
    assert!(
        !names.iter().any(|n| n.starts_with("sources/")),
        "expected no sources/ entries with 0 citations, got {names:?}",
    );
    // citations.json must contain an empty array.
    let mut buf = String::new();
    archive
        .by_name("citations.json")
        .unwrap()
        .read_to_string(&mut buf)
        .unwrap();
    let parsed: serde_json::Value = serde_json::from_str(&buf).expect("citations.json is JSON");
    assert!(
        parsed.is_array(),
        "citations.json must be an array, got {parsed:?}",
    );
    assert_eq!(parsed.as_array().unwrap().len(), 0);
}

#[test]
fn evidence_pack_dedupes_source_excerpts_across_repeated_source_ids() {
    // Two citations sharing the same SourceId — the per-source
    // excerpt files MUST be deduplicated to a single file. Without
    // the de-dup, the second iteration of the `start_file` call
    // would try to write a duplicate entry (some ZIP libraries
    // tolerate this; ours' guard against it).
    let shared_id = SourceId::new();
    let citations = vec![
        citation_for(shared_id, "Source Title", "First use"),
        citation_for(shared_id, "Source Title", "Second use"),
        citation_for(shared_id, "Source Title", "Third use"),
    ];
    let dir = tempfile::tempdir().unwrap();
    let output = dir.path().join("dedupe.zip");
    let artifact = Artifact::new("Dedup Test".into(), ArtifactType::Document, None);

    build_evidence_pack(&artifact, &citations, output.to_str().unwrap()).expect("build");

    let file = std::fs::File::open(&output).unwrap();
    let mut archive = zip::ZipArchive::new(file).expect("zip parses");
    let source_entries: Vec<String> = (0..archive.len())
        .map(|i| archive.by_index(i).unwrap().name().to_string())
        .filter(|n| n.starts_with("sources/"))
        .collect();
    assert_eq!(
        source_entries.len(),
        1,
        "expected exactly 1 sources/ entry for 3 citations sharing one SourceId, got {source_entries:?}",
    );
}

#[test]
fn evidence_pack_unicode_source_title_round_trips_through_excerpt() {
    let citation = citation_for(
        SourceId::new(),
        "日本語 source title — 中文标题 — العربية",
        "テスト目的",
    );
    let dir = tempfile::tempdir().unwrap();
    let output = dir.path().join("unicode.zip");
    let artifact = Artifact::new("ユニコード Test".into(), ArtifactType::Document, None);

    build_evidence_pack(
        &artifact,
        std::slice::from_ref(&citation),
        output.to_str().unwrap(),
    )
    .expect("build");

    let file = std::fs::File::open(&output).unwrap();
    let mut archive = zip::ZipArchive::new(file).expect("zip parses");
    let filename = format!("sources/{}.txt", citation.source_id);
    let mut buf = String::new();
    archive
        .by_name(&filename)
        .expect("source excerpt file exists")
        .read_to_string(&mut buf)
        .expect("source excerpt is UTF-8");
    assert!(
        buf.contains("日本語 source title — 中文标题 — العربية"),
        "unicode source title must survive, got:\n{buf}",
    );
    assert!(
        buf.contains("テスト目的"),
        "unicode used_for must survive, got:\n{buf}",
    );
}

#[test]
fn evidence_pack_artifact_md_includes_metadata_block_and_body() {
    let mut artifact = Artifact::new("With Body".into(), ArtifactType::Document, None);
    artifact.update_content("Body line 1.\nBody line 2.".into());
    let dir = tempfile::tempdir().unwrap();
    let output = dir.path().join("body.zip");
    build_evidence_pack(&artifact, &[], output.to_str().unwrap()).expect("build");

    let file = std::fs::File::open(&output).unwrap();
    let mut archive = zip::ZipArchive::new(file).expect("zip parses");
    let mut buf = String::new();
    archive
        .by_name("artifact.md")
        .unwrap()
        .read_to_string(&mut buf)
        .unwrap();
    assert!(buf.contains("# With Body"));
    assert!(buf.contains("Type: document"));
    // `Artifact::update_content` bumps the version from 1 to 2 as the
    // canonical sign that the artifact's body has been authored beyond
    // the initial empty state. We pin that the metadata block in
    // artifact.md surfaces the post-author version so an auditor
    // reading the evidence pack sees the same version number a sync
    // would report.
    assert!(
        buf.contains("Version: 2"),
        "expected post-update Version: 2 in metadata, got:\n{buf}",
    );
    assert!(buf.contains("Body line 1."));
    assert!(buf.contains("Body line 2."));
    // Section separator between metadata and body.
    assert!(
        buf.contains("\n---\n"),
        "artifact.md must include the `---` metadata/body separator, got:\n{buf}",
    );
}

#[test]
fn evidence_pack_many_citations_produces_one_excerpt_per_unique_source() {
    // 50 citations across 5 unique sources — expect exactly 5
    // sources/*.txt files.
    let mut citations = Vec::new();
    let source_ids: Vec<SourceId> = (0..5).map(|_| SourceId::new()).collect();
    for i in 0..50 {
        let sid = source_ids[i % 5];
        citations.push(citation_for(sid, "Doc", &format!("Use {i}")));
    }
    let dir = tempfile::tempdir().unwrap();
    let output = dir.path().join("many.zip");
    let artifact = Artifact::new("Many".into(), ArtifactType::Document, None);
    build_evidence_pack(&artifact, &citations, output.to_str().unwrap()).expect("build");

    let file = std::fs::File::open(&output).unwrap();
    let mut archive = zip::ZipArchive::new(file).expect("zip parses");
    let source_count = (0..archive.len())
        .filter(|&i| {
            archive
                .by_index(i)
                .is_ok_and(|f| f.name().starts_with("sources/"))
        })
        .count();
    assert_eq!(
        source_count, 5,
        "expected 5 unique source excerpts for 50 citations across 5 sources, got {source_count}",
    );
}
