#[test]
fn markdown_very_long_content_does_not_overflow() {
    // 10k short paragraphs — well past any reasonable stack frame /
    // small-buffer optimisation boundary. The exporter must produce
    // output whose length is monotonically related to the input.
    let mut content = String::new();
    for i in 0..10_000 {
        writeln!(content, "Paragraph {i} body text.\n").unwrap();
    }
    let mut artifact = Artifact::new("Long Doc".into(), ArtifactType::Document, None);
    artifact.update_content(content.clone());

    let out = export_markdown(&artifact, &[]);
    // First and last paragraphs survive the round trip.
    assert!(
        out.contains("Paragraph 0 body text."),
        "expected first paragraph in output",
    );
    assert!(
        out.contains("Paragraph 9999 body text."),
        "expected last paragraph in output",
    );
    // Output is at least as long as the input (excluding the title /
    // footer scaffolding).
    assert!(
        out.len() > content.len(),
        "expected output >= input length, got out.len()={} input.len()={}",
        out.len(),
        content.len(),
    );
}

#[test]
fn html_very_long_content_emits_each_paragraph_separately() {
    // 1k paragraphs is enough to verify the paragraph loop in
    // `emit_text_segment` doesn't drop or merge anything.
    let mut content = String::new();
    for i in 0..1_000 {
        writeln!(content, "Paragraph {i} body.\n").unwrap();
    }
    let mut artifact = Artifact::new("Long HTML".into(), ArtifactType::Document, None);
    artifact.update_content(content);

    let out = export_html(&artifact, &[]);
    let p_count = out.matches("<p>").count();
    assert!(
        p_count >= 1_000,
        "expected at least 1000 <p> tags, got {p_count}",
    );
}

