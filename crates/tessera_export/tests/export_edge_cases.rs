#[test]
fn mermaid_adjacent_blocks_extract_independently() {
    // Two fenced blocks separated only by a single newline — the
    // extractor must surface BOTH, not merge them into one.
    let content =
        "```mermaid\nflowchart LR\nA-->B\n```\n```mermaid\npie\n\"A\" : 50\n\"B\" : 50\n```\n";
    let blocks = mermaid::extract_blocks(content);
    assert_eq!(blocks.len(), 2, "expected 2 blocks, got {blocks:?}");
    assert!(blocks[0].dsl.contains("flowchart"));
    assert!(blocks[1].dsl.contains("pie"));
    assert_eq!(blocks[0].diagram_type, "flowchart");
    assert_eq!(blocks[1].diagram_type, "pie");
}

#[test]
fn mermaid_block_at_very_start_of_content_extracts_cleanly() {
    let content = "```mermaid\nsequenceDiagram\nA->>B: hi\n```\nfollow-up text";
    let blocks = mermaid::extract_blocks(content);
    assert_eq!(blocks.len(), 1);
    assert_eq!(blocks[0].diagram_type, "sequence");
    assert!(blocks[0].dsl.contains("A->>B: hi"));
}

#[test]
fn mermaid_block_at_very_end_of_content_extracts_cleanly() {
    let content = "Prose text first.\n\n```mermaid\nstateDiagram\n[*] --> Idle\n```";
    let blocks = mermaid::extract_blocks(content);
    assert_eq!(blocks.len(), 1);
    assert_eq!(blocks[0].diagram_type, "state");
}

#[test]
fn mermaid_html_export_emits_one_div_per_block_and_one_runtime_script() {
    let content = "```mermaid\nflowchart LR\nA-->B\n```\n\nProse.\n\n```mermaid\npie\n\"X\" : 60\n\"Y\" : 40\n```\n";
    let mut artifact = Artifact::new("Two Diagrams".into(), ArtifactType::Document, None);
    artifact.update_content(content.into());
    let out = export_html(&artifact, &[]);

    // Each diagram must produce exactly one <div class="mermaid">.
    let div_count = out.matches(r#"<div class="mermaid""#).count();
    assert_eq!(
        div_count, 2,
        "expected 2 mermaid divs, got {div_count} in:\n{out}",
    );
    // The mermaid runtime script must be present exactly once (even
    // for multiple blocks).
    let runtime_count = out.matches("https://cdn.jsdelivr.net/npm/mermaid").count();
    assert_eq!(
        runtime_count, 1,
        "expected exactly 1 mermaid runtime script tag, got {runtime_count}",
    );
}

#[test]
fn mermaid_pdf_placeholder_strips_dsl_and_keeps_diagram_type() {
    let block = &mermaid::extract_blocks("```mermaid\nflowchart LR\nA-->B\n```\n")[0];
    let placeholder = mermaid::to_pdf_placeholder(block);
    assert!(
        !placeholder.contains("A-->B"),
        "PDF placeholder must NOT leak DSL, got: {placeholder}",
    );
    assert!(placeholder.contains("flowchart"));
}

#[test]
fn mermaid_markdown_round_trip_preserves_dsl_verbatim_via_to_markdown_block() {
    let original_dsl = "flowchart LR\n    A[Start] -->|next| B(Process)\n    B --> C{Done?}";
    let content = format!("```mermaid\n{original_dsl}\n```\n");
    let blocks = mermaid::extract_blocks(&content);
    assert_eq!(blocks.len(), 1);
    let round_tripped = mermaid::to_markdown_block(&blocks[0]);
    assert!(
        round_tripped.contains(original_dsl),
        "round-trip must preserve original DSL verbatim. Original:\n{original_dsl}\nGot:\n{round_tripped}",
    );
}

