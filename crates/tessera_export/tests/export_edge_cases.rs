//! Edge-case integration tests for the export engine.
//!
//! The inline unit tests in `src/*.rs` cover happy-path output shape;
//! the smoke suite at `tests/phase_smoke_export.rs` verifies that the
//! eight shipping format functions exist and aren't stubbed. This file
//! covers the *boundary* conditions that real users hit and that the
//! happy-path tests miss:
//!
//! * Empty artifacts (no body, no citations).
//! * Very long content (10k-line body that must not blow the stack).
//! * Unicode payloads (CJK, emoji, RTL Hebrew, combining marks,
//!   zero-width joiners, control characters that must NOT be smuggled
//!   into output).
//! * Mermaid edge cases the inline parser tests don't combine:
//!   adjacent blocks separated only by a newline, blocks at the very
//!   start/end of content, long DSL bodies, multiple diagram-type
//!   markers in the same artifact.
//! * Evidence pack edge cases: empty-citation list (must still
//!   produce a valid ZIP with `citations.json` = `[]`), duplicate
//!   source ids across many citations (must produce ONE source file
//!   per id, not N), Unicode source titles round-trip cleanly.
//!
//! Every test asserts a specific, falsifiable property of the output —
//! a stub returning `Default::default()` would fail every assertion
//! here.

use std::fmt::Write;
use std::io::Read;

use tessera_artifacts::Artifact;
use tessera_citations::citation::Citation;
use tessera_core::{ArtifactType, SourceId, SourceType};

use tessera_export::csv::export_csv;
use tessera_export::evidence_pack::build_evidence_pack;
use tessera_export::html::export_html;
use tessera_export::markdown::export_markdown;
use tessera_export::mermaid;

fn citation_for(source_id: SourceId, title: &str, used_for: &str) -> Citation {
    Citation::new(
        source_id,
        SourceType::LocalFile,
        title.to_string(),
        format!("file:///tessera/{}", title.replace(' ', "_")),
        blake3::hash(format!("chunk-{title}").as_bytes())
            .to_hex()
            .to_string(),
        blake3::hash(format!("file-{title}").as_bytes())
            .to_hex()
            .to_string(),
        used_for.to_string(),
        0.87,
    )
}

