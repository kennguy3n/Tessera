#[test]
fn markdown_unicode_title_and_body_round_trip_verbatim() {
    // Markdown is not HTML — escaping is NOT applied at the markdown
    // layer (the consumer's renderer escapes when it converts to HTML).
    // So a unicode payload must round-trip verbatim.
    let mut artifact = Artifact::new(
        "日本語タイトル — 中文标题 — العربية".into(),
        ArtifactType::Document,
        None,
    );
    artifact.update_content(
        "Emoji: \u{1F525} \u{1F3AF} \u{2764}\u{FE0F}\n\
         RTL: שלום עולם\n\
         Combining: e\u{0301} \u{1F468}\u{200D}\u{1F4BB}\n\
         CJK + math: 圆周率 π ≈ 3.14159\n"
            .into(),
    );

    let out = export_markdown(&artifact, &[]);
    assert!(out.contains("日本語タイトル"));
    assert!(out.contains("中文标题"));
    assert!(out.contains("العربية"));
    assert!(out.contains("\u{1F525}"));
    assert!(out.contains("\u{1F468}\u{200D}\u{1F4BB}"));
    assert!(out.contains("שלום עולם"));
    assert!(out.contains("e\u{0301}"));
    assert!(out.contains("圆周率 π ≈ 3.14159"));
    // Output must be valid UTF-8.
    assert!(
        std::str::from_utf8(out.as_bytes()).is_ok(),
        "markdown output must be valid UTF-8",
    );
}

#[test]
fn html_unicode_body_html_escapes_special_chars_but_keeps_non_ascii() {
    // The HTML exporter MUST escape `<`, `>`, `&`, `"`, `'` but MUST
    // preserve non-ASCII unicode literally — it's already valid
    // UTF-8 in the HTML body. A naive `escape_html` implementation
    // that lowercases or strips non-ASCII would fail this test.
    let mut artifact = Artifact::new("Unicode <Title>".into(), ArtifactType::Document, None);
    artifact.update_content("日本語 with <script> tag and & ampersand and \"quote\"".into());
    let out = export_html(&artifact, &[]);
    assert!(
        out.contains("日本語"),
        "unicode body must survive, got:\n{out}"
    );
    // Title rendered as <h1> — must NOT contain literal `<Title>`
    // (would mean it wasn't escaped).
    assert!(
        out.contains("Unicode &lt;Title&gt;"),
        "title must be escaped"
    );
    // Body's `<script>` must be escaped.
    assert!(
        out.contains("&lt;script&gt;"),
        "script tags in body must be escaped, got:\n{out}",
    );
    // `&` and `"` must be escaped.
    assert!(out.contains("&amp;"));
    assert!(out.contains("&quot;"));
    // The raw substring `<script>` (not escaped) must NOT appear in
    // the body (it's fine that we have `<style>`, `<title>` etc as
    // structural tags).
    assert!(
        !out.contains("<script>"),
        "raw <script> must not appear unescaped, got:\n{out}",
    );
}

#[test]
fn csv_unicode_title_with_embedded_quote_is_escaped_via_doubling() {
    // CSV requires `"` inside a quoted field to be doubled to `""`.
    // The artifact title contains a Unicode payload AND a quote.
    let artifact = Artifact::new(
        "日本語 \"quoted\" 標題".into(),
        ArtifactType::Document,
        None,
    );
    let out = export_csv(&artifact, &[]);
    assert!(out.contains("\"日本語 \"\"quoted\"\" 標題\""));
}

